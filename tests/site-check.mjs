import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=n=>fs.readFileSync(path.join(root,n),'utf8');
const html=read('index.html'),js=read('app.js'),css=read('styles.css'),sw=read('sw.js');
assert.match(html,/Public Web Edition · v0\.26/);
assert.match(html,/<script src="\.\/app\.js"><\/script>/);
assert.match(html,/<link rel="stylesheet" href="\.\/styles\.css">/);
assert.doesNotMatch(html,/<script>\s*[\s\S]*?<\/script>/);
assert.match(js,/runtime100Confirm/);
assert.match(js,/OWNER_101_SUBSDK2_SHA/);
assert.match(js,/inspect101Readonly/);
assert.match(js,/activeVerified\.rosterCount===100/);
assert.match(js,/if\(proof\.readonly\)/);
assert.match(js,/if\(b===118\|\|byID\.get\(b\)\?\.staged/);
assert.match(js,/if\(logical===118\|\|logical>118\)/);
assert.match(js,/the P855 101-card Ink Hatcher module must not be replaced/i);
const match=js.match(/const KARTS=(\[[^\n;]+\]);/);
assert(match,'Built-in roster missing');
const karts=JSON.parse(match[1]);
assert.equal(karts.length,101);
assert.equal(karts.at(-1).name,'Ink Hatcher');
assert.equal(karts.at(-1).id,118);
assert.equal(karts.at(-1).native,62);
assert.equal(karts.at(-1).staged,true);
assert.deepEqual(karts.slice(-4).map(k=>k.name),['Shooting Star','Bulldozer','Sparky','Ink Hatcher']);
assert.equal(new Set(karts.map(k=>k.id)).size,101);
const drv=js.match(/const DRIVER_NAMES=(\[[^\n;]+\]);/);
assert(drv,'Driver names list missing');
assert.equal(JSON.parse(drv[1]).length,52);
const ids=new Set();
for(const m of html.matchAll(/<select aria-label="Kart (\d)" id="body-\d">([\s\S]*?)<\/select>/g)){
  ids.add(+m[1]);
  assert.equal((m[2].match(/<option\b[^>]*value="\d+"/g)||[]).length,101,`slot ${m[1]} should list all 101 karts`);
  assert.match(m[2],/<option value="118">Ink Hatcher/);
}
assert.deepEqual([...ids].sort(),[1,2,3,4,5,6,7,8]);
assert.match(html,/id="runtime100Confirm"/);
assert.match(css,/\.runtime100Notice\{/);
assert.match(sw,/clearlane-cpu-studio-public-v026/);
assert.match(sw,/\.\/app\.js/);
assert.match(sw,/\.\/styles\.css/);
const m=JSON.parse(read('manifest.webmanifest'));
assert.equal(m.name,'ClearLane CPU Studio');
for(const f of ['index.html','app.js','styles.css','sw.js','manifest.webmanifest','netlify.toml'])assert(fs.existsSync(path.join(root,f)),f);
assert.match(read('netlify.toml'),/Content-Security-Policy/);
console.log('PASS: 101 karts, 52 drivers, eight 101-choice static slots, exports guarded, PWA cache and security config');

assert.match(js,/native101Profile/);
assert.match(js,/compile101NoIpsSubsdk2/);
assert.match(html,/id="noips101Export"/);
